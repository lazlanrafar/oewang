//! Shared OWE1 test vectors.
//!
//! The Node client in `apps/app` and the Python client in `apps/ai` run the
//! same file. Three implementations of one wire contract will drift unless
//! something holds them to the same bytes, and this is that something.
//!
//! The vectors are committed at `crates/domain/testdata/owe1-vectors.json`.
//! Regenerate deliberately, never casually: a change here is a change to the
//! protocol, and every client has to move with it.
//!
//! ```text
//! REGENERATE_OWE1_VECTORS=1 cargo test -p oewang-domain --test owe1_vectors
//! ```

use std::{fs, path::PathBuf};

use oewang_domain::owe1::{aad, handshake, seal};
use serde_json::json;
use x25519_dalek::{PublicKey, StaticSecret};

/// Fixed inputs. Nothing here is random: a vector must be reproducible on
/// every machine and in every language.
const CLIENT_SECRET: [u8; 32] = [0x11; 32];
const SERVER_SECRET: [u8; 32] = [0x22; 32];
const CLIENT_NONCE: [u8; 16] = [0x33; 16];
const SERVER_NONCE: [u8; 16] = [0x44; 16];
const SESSION_ID: &str = "cs_vectors0000000000000001";
const REQUEST_ID: &str = "01JC0ZYQ8K3M5N7P9R1T3V5W7Y";
const TIMESTAMP: i64 = 1_762_070_523;
const EXPIRES_AT: i64 = 1_762_156_923;
const SEAL_NONCE: [u8; 12] = [0x55; 12];

fn vectors_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("testdata/owe1-vectors.json")
}

fn build() -> serde_json::Value {
    let client_secret = StaticSecret::from(CLIENT_SECRET);
    let server_secret = StaticSecret::from(SERVER_SECRET);
    let client_public = PublicKey::from(&client_secret);
    let server_public = PublicKey::from(&server_secret);

    let keys = handshake::derive_keys(
        &server_secret,
        &client_public,
        &CLIENT_NONCE,
        &SERVER_NONCE,
        SESSION_ID,
    )
    .expect("derivation must succeed for the fixed inputs");

    let transcript = handshake::transcript(
        &client_public.to_bytes(),
        &server_public.to_bytes(),
        &CLIENT_NONCE,
        &SERVER_NONCE,
        SESSION_ID,
        EXPIRES_AT,
        TIMESTAMP,
    );

    // One vector per associated-data shape, each sealed with a fixed nonce so
    // the ciphertext is byte-identical in every language.
    let request_aad = aad::request(
        SESSION_ID,
        "POST",
        "/v1/transactions",
        REQUEST_ID,
        TIMESTAMP,
    );
    let request_plaintext = br#"{"type":"expense","amount":"50000.0000"}"#;
    let sealed_request = seal::seal_with_nonce(
        &keys.client_to_server,
        &request_aad,
        request_plaintext,
        &SEAL_NONCE,
    )
    .unwrap();

    let query_aad = aad::query(SESSION_ID, "GET", "/v1/transactions", REQUEST_ID, TIMESTAMP);
    let query_plaintext = b"type=expense&page=2";
    let sealed_query = seal::seal_with_nonce(
        &keys.client_to_server,
        &query_aad,
        query_plaintext,
        &SEAL_NONCE,
    )
    .unwrap();

    let response_aad = aad::response(SESSION_ID, REQUEST_ID, 201);
    let response_plaintext =
        br#"{"data":{"id":"clx1"},"error":null,"meta":{"request_id":"01JC0ZYQ8K3M5N7P9R1T3V5W7Y"}}"#;
    let sealed_response = seal::seal_with_nonce(
        &keys.server_to_client,
        &response_aad,
        response_plaintext,
        &SEAL_NONCE,
    )
    .unwrap();

    let event_aad = aad::stream_event(SESSION_ID, REQUEST_ID, 0);
    let event_plaintext = br#"{"text":"You spent "}"#;
    let sealed_event = seal::seal_with_nonce(
        &keys.server_to_client,
        &event_aad,
        event_plaintext,
        &SEAL_NONCE,
    )
    .unwrap();

    json!({
        "version": 1,
        "note": "Generated by crates/domain/tests/owe1_vectors.rs. Every client runs these.",
        "inputs": {
            "client_secret": handshake::encode(&CLIENT_SECRET),
            "server_secret": handshake::encode(&SERVER_SECRET),
            "client_public_key": handshake::encode(&client_public.to_bytes()),
            "server_public_key": handshake::encode(&server_public.to_bytes()),
            "client_nonce": handshake::encode(&CLIENT_NONCE),
            "server_nonce": handshake::encode(&SERVER_NONCE),
            "session_id": SESSION_ID,
            "request_id": REQUEST_ID,
            "timestamp": TIMESTAMP,
            "expires_at": EXPIRES_AT,
            "seal_nonce": handshake::encode(&SEAL_NONCE)
        },
        "derived": {
            "k_c2s": handshake::encode(&keys.client_to_server),
            "k_s2c": handshake::encode(&keys.server_to_client),
            "transcript": handshake::encode(&transcript),
            "key_id_of_server_public": handshake::key_id(&server_public.to_bytes())
        },
        "messages": {
            "request": {
                "aad": String::from_utf8(request_aad).unwrap(),
                "plaintext": String::from_utf8(request_plaintext.to_vec()).unwrap(),
                "sealed": sealed_request
            },
            "query": {
                "aad": String::from_utf8(query_aad).unwrap(),
                "plaintext": String::from_utf8(query_plaintext.to_vec()).unwrap(),
                "sealed": sealed_query
            },
            "response": {
                "aad": String::from_utf8(response_aad).unwrap(),
                "plaintext": String::from_utf8(response_plaintext.to_vec()).unwrap(),
                "sealed": sealed_response
            },
            "stream_event": {
                "aad": String::from_utf8(event_aad).unwrap(),
                "plaintext": String::from_utf8(event_plaintext.to_vec()).unwrap(),
                "sealed": sealed_event
            }
        }
    })
}

#[test]
fn should_match_the_committed_vectors() {
    let generated = build();
    let path = vectors_path();

    if std::env::var("REGENERATE_OWE1_VECTORS").is_ok() {
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(
            &path,
            format!("{}\n", serde_json::to_string_pretty(&generated).unwrap()),
        )
        .unwrap();
        eprintln!("regenerated {}", path.display());
        return;
    }

    let committed: serde_json::Value = serde_json::from_str(
        &fs::read_to_string(&path).expect("vectors file missing; regenerate it"),
    )
    .expect("vectors file is not valid JSON");

    assert_eq!(
        generated, committed,
        "OWE1 output changed. This is a protocol change: every client must move with it. \
         Regenerate deliberately with REGENERATE_OWE1_VECTORS=1."
    );
}

/// The vectors are only worth anything if they round-trip, so prove it here
/// rather than trusting the generator.
#[test]
fn should_open_every_sealed_vector() {
    let client_secret = StaticSecret::from(CLIENT_SECRET);
    let server_secret = StaticSecret::from(SERVER_SECRET);

    // Both sides derive the same keys from their own half of the exchange.
    let server_side = handshake::derive_keys(
        &server_secret,
        &PublicKey::from(&client_secret),
        &CLIENT_NONCE,
        &SERVER_NONCE,
        SESSION_ID,
    )
    .unwrap();
    let client_side = handshake::derive_keys(
        &client_secret,
        &PublicKey::from(&server_secret),
        &CLIENT_NONCE,
        &SERVER_NONCE,
        SESSION_ID,
    )
    .unwrap();
    assert_eq!(server_side, client_side);

    let vectors = build();
    let messages = &vectors["messages"];

    for (name, key) in [
        ("request", &client_side.client_to_server),
        ("query", &client_side.client_to_server),
        ("response", &client_side.server_to_client),
        ("stream_event", &client_side.server_to_client),
    ] {
        let message = &messages[name];
        let sealed: seal::SealedBody = serde_json::from_value(message["sealed"].clone()).unwrap();
        let aad = message["aad"].as_str().unwrap().as_bytes();

        let opened =
            seal::open(key, aad, &sealed).unwrap_or_else(|e| panic!("{name} failed to open: {e}"));

        assert_eq!(
            String::from_utf8(opened).unwrap(),
            message["plaintext"].as_str().unwrap(),
            "{name} round trip"
        );
    }
}
