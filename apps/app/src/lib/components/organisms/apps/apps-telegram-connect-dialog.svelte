<script lang="ts">
	/**
	 * Connect Telegram, as the old app's dialog: a QR code for a phone, a
	 * button that opens the bot on this device, and a copy of the link.
	 *
	 * The link carries a one-time token for the signed-in member (D85). It is
	 * shown here and nowhere else: not in the address bar, not in a log. The
	 * QR is drawn on the server, so the page needs no QR library.
	 */
	import Check from '@lucide/svelte/icons/check';
	import Copy from '@lucide/svelte/icons/copy';

	import * as Dialog from '$lib/components/atoms/dialog';
	import { Button } from '$lib/components/atoms/button';
	import { t } from '$lib/i18n';

	import AppsLogo from './apps-logo.svelte';

	let {
		open = $bindable(false),
		deepLink,
		qrSvg,
		onOpenChange
	}: {
		open?: boolean;
		deepLink: string;
		/** SVG markup the server generated from `deepLink`. */
		qrSvg: string;
		onOpenChange?: (open: boolean) => void;
	} = $props();

	let copied = $state(false);
	let copiedTimer: ReturnType<typeof setTimeout> | undefined;

	async function copy() {
		try {
			await navigator.clipboard.writeText(deepLink);
			copied = true;
			clearTimeout(copiedTimer);
			copiedTimer = setTimeout(() => (copied = false), 2000);
		} catch {
			copied = false;
		}
	}
</script>

<Dialog.Root bind:open {onOpenChange}>
	<Dialog.Content class="overflow-hidden p-0 sm:max-w-[460px]">
		<Dialog.Header class="p-8 pb-0">
			<Dialog.Title class="text-xl">{t('apps.telegram_connect_title')}</Dialog.Title>
			<Dialog.Description>{t('apps.telegram_connect_description')}</Dialog.Description>
		</Dialog.Header>

		<div class="flex flex-col items-center gap-6 px-8 pb-8">
			<div class="border bg-white p-3">
				<!-- Generated by the server from a link it minted; no user text
				     reaches this markup. -->
				<div class="size-[200px] [&_svg]:size-full" role="img" aria-label={t('apps.telegram_qr_label')}>
					{@html qrSvg}
				</div>
			</div>

			<div class="grid w-full grid-cols-2 gap-3">
				<Button href={deepLink} target="_blank" rel="noopener noreferrer">
					<AppsLogo id="telegram" class="size-4" />
					{t('apps.telegram_open_bot')}
				</Button>
				<Button variant="outline" onclick={copy}>
					{#if copied}
						<Check />
						{t('apps.copied')}
					{:else}
						<Copy />
						{t('apps.copy_link')}
					{/if}
				</Button>
			</div>

			<p class="text-subtle max-w-[300px] text-center text-xs">{t('apps.telegram_connect_footer')}</p>
		</div>
	</Dialog.Content>
</Dialog.Root>
