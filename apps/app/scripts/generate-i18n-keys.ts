/**
 * Generate the TranslationKey union from en.json.
 *
 * Without this, a typo in a key renders the key itself and nobody notices
 * until a screenshot. With it, the build fails.
 *
 *   bun run scripts/generate-i18n-keys.ts
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const i18nDir = join(here, '../src/lib/i18n');

function paths(value: unknown, prefix = ''): string[] {
	if (typeof value === 'string') return [prefix];
	if (typeof value !== 'object' || value === null) return [];

	return Object.entries(value).flatMap(([key, child]) =>
		paths(child, prefix ? `${prefix}.${key}` : key)
	);
}

const dictionary = JSON.parse(readFileSync(join(i18nDir, 'en.json'), 'utf8'));
const keys = paths(dictionary).sort();

const output = `// Generated by scripts/generate-i18n-keys.ts. Do not edit.
// Run \`bun run i18n:keys\` after changing en.json.

export type TranslationKey =
${keys.map((key) => `\t| '${key}'`).join('\n')};
`;

writeFileSync(join(i18nDir, 'keys.ts'), output);
console.log(`generated ${keys.length} translation keys`);
