#!/usr/bin/env python3
"""Generate docs/ENV_VARS.md from the three configuration modules.

Written by hand, a configuration reference is wrong within a month: a
variable is added in one place and the table is updated in another, or it
is not. This reads the code that actually reads the environment, so the
only way to change the document is to change the configuration.

What it reads:

- `apps/api/crates/server/src/config.rs`, through the three helpers that
  name a variable: `required("X")`, `optional("X")` and `parse_or("X", d)`.
- `apps/ai/app/config.py`, through the `Settings` fields, which
  `pydantic-settings` reads from the uppercased field name.
- `apps/app/src/**`, through `process.env.X`.

Run it from the repository root:

    python3 scripts/env-vars.py            # write docs/ENV_VARS.md
    python3 scripts/env-vars.py --check    # fail if the file is stale

`--check` is what CI runs. It is the half that makes this worth having.
"""

from __future__ import annotations

import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "ENV_VARS.md"

API_CONFIG = ROOT / "apps/api/crates/server/src/config.rs"
AI_CONFIG = ROOT / "apps/ai/app/config.py"
APP_SOURCE = ROOT / "apps/app/src"

#: Variables whose value is a secret. Listed here rather than guessed from
#: the name, because `FX_ACCESS_KEY` is one and `S3_BUCKET` is not, and a
#: heuristic on the word "key" gets both wrong eventually (OPS-3).
SECRETS = {
    "DATABASE_URL",
    "JWT_SECRET",
    "AI_SERVICE_API_KEY",
    "AI_API_KEY",
    "RESEND_API_KEY",
    "FX_ACCESS_KEY",
    "S3_SECRET_ACCESS_KEY",
    "S3_ACCESS_KEY_ID",
}


def api_variables() -> dict[str, str | None]:
    """`required`, `optional` and `parse_or` are the only three ways the
    API names a variable, which is what makes this parseable at all."""
    source = API_CONFIG.read_text()
    found: dict[str, str | None] = {}

    for name in re.findall(r'required\("([A-Z0-9_]+)"\)', source):
        found[name] = None
    for name in re.findall(r'optional\("([A-Z0-9_]+)"\)', source):
        found.setdefault(name, "")
    for name, default in re.findall(
        r'parse_or\(\s*"([A-Z0-9_]+)",\s*([^)]+?)\)', source, re.S
    ):
        # A default may be a literal or a named constant; either way the
        # trailing comma from the call site is not part of it.
        found.setdefault(name, " ".join(default.split()).rstrip(","))

    return found


def ai_variables() -> dict[str, str]:
    """Every `Settings` field, which pydantic reads from the uppercased
    name. The type annotation is skipped; the default is the useful half."""
    source = AI_CONFIG.read_text()
    body = source.split("class Settings(BaseSettings):", 1)[1]
    body = body.split("\n    def ", 1)[0]

    found: dict[str, str] = {}
    for field, default in re.findall(
        r"^    ([a-z][a-z0-9_]*)\s*:\s*[^=\n]+=\s*(.+)$", body, re.M
    ):
        if field == "model_config":
            continue
        found[field.upper()] = default.strip()
    return found


def app_variables() -> set[str]:
    names: set[str] = set()
    for path in APP_SOURCE.rglob("*.ts"):
        names.update(re.findall(r"process\.env\.([A-Z0-9_]+)", path.read_text()))
    for path in APP_SOURCE.rglob("*.svelte"):
        names.update(re.findall(r"process\.env\.([A-Z0-9_]+)", path.read_text()))
    return names


def row(name: str, default: str | None) -> str:
    if name in SECRETS:
        shown = "secret"
    elif default is None:
        shown = "required"
    elif default == "":
        shown = "unset"
    else:
        shown = f"`{default}`"
    return f"| `{name}` | {shown} |"


def render() -> str:
    api = api_variables()
    ai = ai_variables()
    app = sorted(app_variables())

    shared = sorted(set(api) & set(ai))

    lines = [
        "# Environment variables",
        "",
        "**Generated by `scripts/env-vars.py` from the three configuration",
        "modules. Do not edit by hand: change the configuration and run it",
        "again.** CI runs `--check` and fails when this file is stale.",
        "",
        f"Last generated {date.today().isoformat()}.",
        "",
        "A value shown as `secret` is never printed, logged or committed",
        "(OPS-3). `required` means the process refuses to start without it.",
        "Anything else is the default the code falls back to.",
        "",
        "See [hardening](security/hardening.md#secrets) for how secrets are",
        "supplied and [deployment](deployment.md) for what each service",
        "needs where.",
        "",
        "## apps/api",
        "",
        "Read by `apps/api/crates/server/src/config.rs` at startup.",
        "",
        "| Variable | Default |",
        "|---|---|",
    ]
    lines += [row(name, api[name]) for name in sorted(api)]

    lines += [
        "",
        "## apps/ai",
        "",
        "Read by `apps/ai/app/config.py`. This process is never given",
        "`DATABASE_URL`, `JWT_SECRET`, `S3_SECRET_ACCESS_KEY` or",
        "`RESEND_API_KEY`, and refuses to start if one arrives (D3, D4).",
        "",
        "| Variable | Default |",
        "|---|---|",
    ]
    lines += [row(name, ai[name]) for name in sorted(ai)]

    lines += [
        "",
        "## apps/app",
        "",
        "Read through `process.env` in server-side code only. Nothing here",
        "reaches the browser (D5).",
        "",
        "| Variable |",
        "|---|",
    ]
    lines += [f"| `{name}` |" for name in app]

    lines += [
        "",
        "## Shared by the API and the AI service",
        "",
        "These must agree across the two processes, and a deployment that",
        "sets one and not the other fails at the first call rather than at",
        "startup.",
        "",
        "| Variable |",
        "|---|",
    ]
    lines += [f"| `{name}` |" for name in shared]
    lines.append("")

    return "\n".join(lines)


def main() -> int:
    rendered = render()

    if "--check" in sys.argv:
        if not OUTPUT.exists():
            print(f"{OUTPUT} does not exist; run scripts/env-vars.py")
            return 1
        current = OUTPUT.read_text()
        # The date line changes every day and says nothing about whether
        # the tables are right, so it is not what staleness means.
        strip = lambda text: "\n".join(  # noqa: E731
            line for line in text.splitlines() if not line.startswith("Last generated")
        )
        if strip(current) != strip(rendered):
            print(f"{OUTPUT} is stale; run scripts/env-vars.py")
            return 1
        print(f"{OUTPUT} is up to date")
        return 0

    OUTPUT.write_text(rendered)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
